STRINGS: dict[str, dict[str, str]] = {LANG_ZH: _ZH, LANG_EN: _EN}


def normalize_lang(code: object) -> str:
    return LANG_EN if str(code).lower().startswith("en") else LANG_ZH


def tr(key: str, lang: str = LANG_ZH, **kwargs: object) -> str:
    """Return the translated string for ``key`` with ``str.format`` applied."""
    table = STRINGS.get(normalize_lang(lang), _ZH)
    template = table.get(key, _ZH.get(key, key))
    if not kwargs:
        return template
    try:
        return template.format(**kwargs)
    except (KeyError, IndexError, ValueError):
        return template
